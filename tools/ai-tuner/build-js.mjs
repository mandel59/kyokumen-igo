// Generate an isolated JS instance factory from the shipped v2 WASM.
import assert from 'node:assert/strict';
import {spawnSync} from 'node:child_process';
import {mkdirSync,readFileSync,writeFileSync} from 'node:fs';
import {createHash} from 'node:crypto';
import {fileURLToPath} from 'node:url';
const here=new URL('./',import.meta.url),root=new URL('../../',here);
const input=new URL('dist/ai-engine.wasm',root),output=new URL('dist/ai-engine.generated.js',root);
const target=new URL('target/browser-wasm/',here);mkdirSync(target,{recursive:true});
const version=JSON.parse(readFileSync(new URL('node_modules/binaryen/package.json',here))).version;
assert.equal(version,'132.0.0','Run npm ci --prefix tools/ai-tuner');
const converted=new URL('ai-engine.mjs',target);
const result=spawnSync(process.execPath,[fileURLToPath(new URL('node_modules/binaryen/bin/wasm2js',here)),
 fileURLToPath(input),'--all-features','-O','-o',fileURLToPath(converted)],{encoding:'utf8',maxBuffer:8*1024*1024});
if(result.error)throw result.error;
if(result.status!==0)throw new Error('wasm2js failed: '+result.stderr.slice(0,8000));
const raw=readFileSync(converted,'utf8').replaceAll('\r\n','\n').replace(/[\t ]+$/gm,''),marker='var retasmFunc = asmFunc({\n});';
const split=raw.indexOf(marker);assert.ok(split>0&&raw.indexOf(marker,split+1)===-1,'Review changed wasm2js output');
assert.match(raw.slice(split),/export var ai_search = retasmFunc.ai_search;/);
// All mutable helpers must be inside the factory so instances cannot share memory.
const sha=createHash('sha256').update(readFileSync(input)).digest('hex');
const generated='// Generated by tools/ai-tuner/build-js.mjs; do not edit.\n// Source WASM SHA-256: '+sha+
 '\n// Binaryen '+version+' wasm2js --all-features -O. Helpers: Apache-2.0; see licenses/Binaryen-LICENSE.txt.\n'+
 '// Copyright 2015 WebAssembly Community Group participants. Output modified into an isolated instance factory.\n'+
 '// Rust runtime notices: licenses/rust/.\nexport function instantiate() {\n'+raw.slice(0,split)+'\nreturn asmFunc({});\n}\n';
if(process.argv.includes('--check'))assert.equal(readFileSync(output,'utf8'),generated,'Generated JS is stale. Run node tools/ai-tuner/build-wasm.mjs');
else writeFileSync(output,generated);
console.log('Generated v2 JS '+(process.argv.includes('--check')?'matches WASM':'built')+' ('+Buffer.byteLength(generated)+' bytes).');
